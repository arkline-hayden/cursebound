#!/usr/bin/env node
// Scans apps/client/public/audio/{sfx,amb,stingers}/*.mp3 and writes apps/client/src/game/audio/sfxFiles.generated.ts:
// which recorded sound files exist, grouped by cue (foo_01.mp3, foo_02.mp3 -> foo: [2 variations]). The audio engine
// plays a file when its cue has one and falls back to the synthesized version otherwise. Run after adding files
// (npm run audio:manifest); scripts/start.mjs and tools/audio/generate.mjs run it too.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const pub = path.join(root, 'apps/client/public/audio');
const out = path.join(root, 'apps/client/src/game/audio/sfxFiles.generated.ts');
const FOLDERS = ['sfx', 'amb', 'stingers'];

const files = FOLDERS.flatMap((d) => {
  const dir = path.join(pub, d);
  return fs.existsSync(dir) ? fs.readdirSync(dir).filter((f) => /^[a-z0-9_]+\.mp3$/.test(f)).sort().map((f) => `${d}/${f}`) : [];
});
const groups = {};
for (const f of files) {
  const base = path.basename(f, '.mp3');
  const m = /^(.*)_(\d{2})$/.exec(base);
  const key = m ? m[1] : base;
  (groups[key] ??= []).push(f);
}
const songs = fs.existsSync(pub) ? fs.readdirSync(pub).filter((f) => /^song-[a-z0-9-]+\.mp3$/.test(f)).map((f) => f.slice(0, -4)).sort() : [];
const body = Object.keys(groups).sort().map((k) => `  ${k}: [${groups[k].map((f) => `'${f}'`).join(', ')}],`).join('\n');
const text = `// Generated by scripts/audio-manifest.mjs from apps/client/public/audio/{sfx,amb,stingers}. Do not edit by hand.
/** Recorded sound files per cue (paths under /audio/: sfx/ effects, amb/ ambience loops, stingers/ music stingers). */
export const SFX_FILES: Record<string, readonly string[]> = {
${body}
};

/** Recorded music tracks present under /audio/ (file stems: song-title, song-floor-forge, song-boss-core…). */
export const MUSIC_FILES: readonly string[] = [${songs.map((x) => `'${x}'`).join(', ')}];
`;
const prev = fs.existsSync(out) ? fs.readFileSync(out, 'utf8') : '';
if (prev.replace(/\r\n/g, '\n') !== text) fs.writeFileSync(out, text);
console.log(`[audio] ${files.length} sound files for ${Object.keys(groups).length} cues`);

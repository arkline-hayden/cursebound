#!/usr/bin/env node
// Scans apps/client/public/audio/sfx/*.mp3 and writes apps/client/src/game/audio/sfxFiles.generated.ts: which recorded
// sound files exist, grouped by cue (foo_01.mp3, foo_02.mp3 -> foo: [2 variants]). The audio engine plays a file when
// its cue has one and falls back to the synthesized recipe otherwise. Run after adding files (npm run audio:manifest);
// scripts/start.mjs and the client build run it too.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const dir = path.join(root, 'apps/client/public/audio/sfx');
const out = path.join(root, 'apps/client/src/game/audio/sfxFiles.generated.ts');

const files = fs.existsSync(dir) ? fs.readdirSync(dir).filter((f) => /^[a-z0-9_]+\.mp3$/.test(f)).sort() : [];
const groups = {};
for (const f of files) {
  const base = f.replace(/\.mp3$/, '');
  const m = /^(.*)_(\d{2})$/.exec(base);
  const key = m ? m[1] : base;
  (groups[key] ??= []).push(f);
}
const body = Object.keys(groups).sort().map((k) => `  ${k}: [${groups[k].map((f) => `'${f}'`).join(', ')}],`).join('\n');
const text = `// Generated by scripts/audio-manifest.mjs from apps/client/public/audio/sfx. Do not edit by hand.
/** Recorded sound files per cue (file names under /audio/sfx/). */
export const SFX_FILES: Record<string, readonly string[]> = {
${body}
};
`;
const prev = fs.existsSync(out) ? fs.readFileSync(out, 'utf8') : '';
if (prev.replace(/\r\n/g, '\n') !== text) fs.writeFileSync(out, text);
console.log(`[audio] ${files.length} sound files for ${Object.keys(groups).length} cues`);
